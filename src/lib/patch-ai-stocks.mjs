#!/usr/bin/env node
// Rewrites the AI_STOCKS block in src/lib/ai-data.ts from the Yahoo dump.
//
// Split out from patch-site-data.mjs on purpose: that script patches values
// field-by-field into hand-maintained literals in site-data.ts, because those
// rows carry curated fields (index P/E, ETF exposure labels) a fetcher must not
// clobber. AI_STOCKS has no curated fields at all — every column comes from
// Yahoo — so the whole block is regenerated, which is simpler and can't drift.
//
// Run:  npm run fetch:ai && npm run patch:ai

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const targetPath = resolve(root, "src/lib/ai-data.ts");
const dumpPath = resolve(root, "src/lib/yahoo-data.json");

const START = "/* AI_STOCKS:START — generated by patch-ai-stocks.mjs; do not edit by hand */";
const END = "/* AI_STOCKS:END */";

const dump = JSON.parse(readFileSync(dumpPath, "utf8"));
const rows = dump.aiStocks ?? [];

if (rows.length === 0) {
  console.error(
    "✗ no aiStocks in yahoo-data.json — run `npm run fetch:ai` first.\n" +
      "  (A partial `--only=` run carries other sections over, so an empty\n" +
      "   aiStocks array means the AI section genuinely was not fetched.)",
  );
  process.exit(1);
}

/* Sparklines dominate the file — 156 floats per row, 24 rows. Emitted on one
   line each so the block stays roughly readable in a diff: a changed quote
   shows as a handful of changed lines rather than 3,700. */
const stockLiteral = (s) =>
  `  {
    symbol: ${JSON.stringify(s.symbol)},
    ticker: ${JSON.stringify(s.ticker)},
    company: ${JSON.stringify(s.company)},
    layer: ${JSON.stringify(s.layer)},
    currency: ${JSON.stringify(s.currency)},
    value: ${s.value},
    dailyChange: ${s.dailyChange},
    weekChange: ${s.weekChange},
    monthChange: ${s.monthChange},
    ytdChange: ${s.ytdChange},
    high52w: ${s.high52w},
    low52w: ${s.low52w},
    realizedVol: ${s.realizedVol ?? "undefined"},
    sparkline: [${s.sparkline.join(", ")}],
  },`;

// Latest observation date across the universe — what the page shows as "as of".
const asOf = rows.map((r) => r.asOf).sort().at(-1);

const block = `${START}
export const AI_STOCKS: AIStock[] = [
${rows.map(stockLiteral).join("\n")}
];

/** Latest close date across the AI universe, ISO yyyy-mm-dd. */
export const AI_STOCKS_ASOF = ${JSON.stringify(asOf)};
${END}`;

const src = readFileSync(targetPath, "utf8");
const startIdx = src.indexOf(START);
const endIdx = src.indexOf(END);

if (startIdx === -1 || endIdx === -1) {
  console.error(`✗ markers not found in ${targetPath} — expected ${START} … ${END}`);
  process.exit(1);
}

const patched = src.slice(0, startIdx) + block + src.slice(endIdx + END.length);
writeFileSync(targetPath, patched);

console.log(`✓ patched ${rows.length} AI stocks into src/lib/ai-data.ts (as of ${asOf})`);
